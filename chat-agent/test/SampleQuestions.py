"""预定义测试问题集。

作为常量持有类（对照 Java 中的常量类），供 SampleQuestionsTest 依次驱动主图。
每条问题都覆盖一种典型的工具使用形态（多独立根 / 依赖链 / 扇入聚合 /
共享依赖 / 参数缺失 / 能力缺失）。
"""

from __future__ import annotations


class SampleQuestions:
    """主图回归用的样例问题集合。"""

    #: 覆盖不同拆分形态的样例问题；索引即样例编号。
    SAMPLE_QUESTIONS: list[str] = [
        # 0) 多个独立根 + 子树内前驱依赖（基线）
        "请帮我获取最近的金价和油价并且帮我比较杭州和上海旅馆均价并给建议",
        # 1) 纯并列、无依赖：应是扁平兄弟，不要过度下拆
        "帮我查一下杭州的天气和上海的天气",
        # 2) 换算依赖链：金价(USD) + 汇率(USD→CNY) → 换算结果依赖前两者
        "帮我获取最近的金价并换算成人民币",
        # 3) 顺序依赖：搜索可预订旅馆 → 预订；预订依赖搜索确定的具体旅馆
        "帮我在杭州找一家可预订的旅馆并预订两晚",
        # 4) 聚合 + 解释：金价/油价并列 → 金油比依赖两者；市场原因为独立并列任务
        "帮我算金油比并解释最近的变化原因",
        # 5) 三个独立根，其中一个带依赖子树
        "帮我查杭州天气、获取最新油价，并比较杭州和上海的旅馆均价给出住宿建议",
        # 6) 宽依赖扇入：天气×2 + 旅馆均价×2 共 4 个并列叶子 → 综合建议依赖全部
        "我下周想去杭州或上海出差，帮我对比两地的天气和旅馆均价，给出去哪个城市的建议",
        # 7) 共享依赖：金价、油价分别换算成人民币，都依赖同一份汇率
        "把最近的金价和油价都换算成人民币后告诉我",
        # 8) 混合：独立任务 + 顺序依赖链（查天气 / 搜索→预订 / 取金价）
        "帮我规划去上海的行程：查一下上海天气，找一家可预订的旅馆并预订一晚，同时告诉我最近的金价",
        # 9) 参数缺失型：未给城市，测试是否脑补前置或保持最小拆解
        "帮我找便宜的旅馆",
        # 10) 能力缺失型：没有趋势类工具，测试是否硬拆或臆造步骤
        "帮我分析最近三天杭州旅馆价格的趋势",
    ]

    @classmethod
    def labeled(cls) -> list[tuple[str, str]]:
        """返回带标签的 ``(标签, 问题)`` 列表，标签形如 ``sample 0``。"""
        return [
            (f"sample {index}", question)
            for index, question in enumerate(cls.SAMPLE_QUESTIONS)
        ]
